"""Pack the hair lock textures baked by godot/hair-design (--mode=bake) for the game.

Reads .scratch/hair-design/raw/{silver,silver_alpha,spectral}.png (2x, frames stacked top to bottom), box-filters them
to 1x and writes:
  src/img/hair_silver.webp    RGBA: the opaque colour pass with the alpha pass as its alpha (straight alpha), so it draws
                              normally ('source-over') onto Yūrei's locks
  src/img/hair_spectral.webp  RGB on black, added ('lighter') onto Mugen's locks
  src/js/34c-hair-sheets.js   HAIR_SHEETS: frame size, count and playback rate of each
Run from the repo root:  python -I tools/hair-design/pack.py [--preview]
--preview also writes .scratch/hair-design/strips_preview.png (each strip over a dark backdrop, 3x).
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
RAW = os.path.join(ROOT, '.scratch', 'hair-design', 'raw')
IMG = os.path.join(ROOT, 'src', 'img')
SS = 2
SHEETS = {
    'silver': {'n': 8, 'cw': 256, 'ch': 48, 'fps': 6, 'alpha': 1},
    'spectral': {'n': 16, 'cw': 256, 'ch': 48, 'fps': 14, 'add': 1},
}


def shrink(im):
    return im.resize((im.width // SS, im.height // SS), Image.BOX)


def main():
    out = {}
    # silver: the opaque colour pass with the alpha pass as its alpha (straight alpha, exact)
    col = shrink(Image.open(os.path.join(RAW, 'silver.png')).convert('RGB'))
    alp = shrink(Image.open(os.path.join(RAW, 'silver_alpha.png')).convert('L'))
    silver = col.copy()
    silver.putalpha(alp)
    silver.save(os.path.join(IMG, 'hair_silver.webp'), 'WEBP', quality=90, method=6)
    spectral = shrink(Image.open(os.path.join(RAW, 'spectral.png')).convert('RGB'))
    spectral.save(os.path.join(IMG, 'hair_spectral.webp'), 'WEBP', quality=88, method=6)
    lines = []
    for name, d in SHEETS.items():
        meta = dict(img='__IMG(hair_%s.webp)__' % name, **d)
        lines.append('  %s: %s' % (name, json.dumps(meta).replace('"img"', 'img').replace('"', "'")))
        out[name] = os.path.getsize(os.path.join(IMG, 'hair_%s.webp' % name))
    js = ('/* KAGE: the hair lock textures designed and baked in Godot (godot/hair-design; generated by\n'
          '   tools/hair-design/pack.py; do not edit). Each is one strip per frame, stacked top to bottom: x runs along a lock\n'
          '   (the root at 0), y across it (its upper edge at 0). silver is drawn normally (alpha), spectral is added.\n'
          '   Mapped onto every lock segment by segment by 21-characters/kage/armory/hair.js. */\n'
          'const HAIR_SHEETS = {\n' + ',\n'.join(lines) + '\n};\n')
    js = js.replace("'n':", 'n:').replace("'cw':", 'cw:').replace("'ch':", 'ch:').replace("'fps':", 'fps:').replace("'alpha':", 'alpha:').replace("'add':", 'add:')
    with open(os.path.join(ROOT, 'src', 'js', '34c-hair-sheets.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    for k, v in out.items():
        print('%s: %.1f KB' % (k, v / 1024))
    if '--preview' in sys.argv:
        bg = (26, 13, 20)
        w = 256 * 3
        prev = Image.new('RGB', (w * 2 + 30, 48 * 3 * 4 + 50), bg)
        for i in range(4):
            fr = silver.crop((0, i * 2 * 48, 256, i * 2 * 48 + 48)).resize((w, 144), Image.LANCZOS)
            base = Image.new('RGBA', fr.size, bg + (255,))
            prev.paste(Image.alpha_composite(base, fr).convert('RGB'), (10, 10 + i * 150))
            sp = spectral.crop((0, i * 4 * 48, 256, i * 4 * 48 + 48)).resize((w, 144), Image.LANCZOS)
            prev.paste(sp, (w + 20, 10 + i * 150))
        prev.save(os.path.join(ROOT, '.scratch', 'hair-design', 'strips_preview.png'))


if __name__ == '__main__':
    main()
