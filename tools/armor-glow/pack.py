#!/usr/bin/env python3
"""Pack the Godot-baked armor-glow sheets for the game.

Reads the raw 2x PNG sheets written by godot/armor-glow/Bake.gd (default .scratch/armor-glow/raw), box-filters them down
to 1x, writes src/img/armor_glow_<name>.webp (RGB, additive on black) and the generated data file
src/js/34b-armor-glow-sheets.js, and (with --preview) contact sheets into .scratch/armor-glow/ for review.

  python -I tools/armor-glow/pack.py [--raw DIR] [--quality 85] [--preview]
"""
import argparse
import os
import sys
from PIL import Image, ImageChops

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

# name: (cols, cell w, cell h, frames, fps, origin x, origin y)
SHEETS = {
    'halo':           (8, 256, 256, 24, 12, 128, 128),
    'flame_violet':   (8, 128, 192, 16, 14, 64, 186),
    'flame_crimson':  (8, 128, 192, 16, 14, 64, 186),
    'lightning_gold': (6, 192, 192, 12, 20, 96, 96),
    'wisp_pale':      (8, 128, 192, 16, 14, 64, 186),
}
LOOPS = {'halo', 'flame_violet', 'flame_crimson', 'wisp_pale'}  # seamless by construction
BG = (0x1a, 0x0d, 0x14)


def frame(sheet, name, i):
    cols, cw, ch, n, *_ = SHEETS[name]
    x, y = (i % cols) * cw, (i // cols) * ch
    return sheet.crop((x, y, x + cw, y + ch))


def over_bg(img):
    """Additive composite on the game's dark floor colour (what canvas 'lighter' does)."""
    return ImageChops.add(Image.new('RGB', img.size, BG), img)


def preview(name, sheet, outdir):
    cols, cw, ch, n, *_ = SHEETS[name]
    # 1) the whole sheet at 1x over the dark background
    over_bg(sheet).save(os.path.join(outdir, f'{name}_sheet.png'))
    # 2) three frames at 3x (nearest-free: bicubic) + the loop seam n-1 | 0 | 1
    ids = [0, n // 3, 2 * n // 3]
    z = 3
    strip = Image.new('RGB', (cw * z * 3, ch * z))
    for k, i in enumerate(ids):
        strip.paste(over_bg(frame(sheet, name, i)).resize((cw * z, ch * z), Image.BICUBIC), (k * cw * z, 0))
    strip.save(os.path.join(outdir, f'{name}_zoom.png'))
    seam = Image.new("RGB", (cw * 2 * 6, ch * 2))
    for k, i in enumerate([n - 2, n - 1, 0, 1, 2, 3][:6]):
        seam.paste(over_bg(frame(sheet, name, i)).resize((cw * 2, ch * 2), Image.BICUBIC), (k * cw * 2, 0))
    seam.save(os.path.join(outdir, f'{name}_seam.png'))
    # loop-continuity report: mean abs difference between consecutive frames, incl. the n-1 -> 0 wrap
    import statistics
    diffs = []
    for i in range(n):
        a = frame(sheet, name, i)
        b = frame(sheet, name, (i + 1) % n)
        d = ImageChops.difference(a, b).convert('L')
        diffs.append(sum(d.tobytes()) / (cw * ch))
    wrap = diffs[-1]
    mid = statistics.mean(diffs[:-1])
    print(f'  {name}: mean frame-to-frame diff {mid:.2f}, wrap (n-1 -> 0) {wrap:.2f}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--raw', default=os.path.join(ROOT, '.scratch', 'armor-glow', 'raw'))
    ap.add_argument('--quality', type=int, default=85)
    ap.add_argument('--preview', action='store_true')
    ap.add_argument('--no-write', action='store_true', help='only make previews, leave src/ alone')
    args = ap.parse_args()

    img_dir = os.path.join(ROOT, 'src', 'img')
    prev_dir = os.path.join(ROOT, '.scratch', 'armor-glow')
    os.makedirs(prev_dir, exist_ok=True)
    lines = []
    for name, (cols, cw, ch, n, fps, ox, oy) in SHEETS.items():
        src = os.path.join(args.raw, f'{name}.png')
        if not os.path.exists(src):
            sys.exit(f'missing {src} - run the Godot bake first (see godot/armor-glow/README.md)')
        big = Image.open(src).convert('RGB')
        rows = -(-n // cols)
        w, h = cols * cw, rows * ch
        assert big.size[0] % w == 0 and big.size[1] % h == 0, f'{name}: {big.size} is not a multiple of {w}x{h}'
        ss = big.size[0] // w
        sheet = big.resize((w, h), Image.BOX) if ss > 1 else big
        out = os.path.join(img_dir, f'armor_glow_{name}.webp')
        if not args.no_write:
            sheet.save(out, 'WEBP', quality=args.quality, method=6)
            print(f'{name}: {w}x{h}, {os.path.getsize(out) / 1024:.1f} KB -> {os.path.relpath(out, ROOT)}')
        if args.preview:
            preview(name, sheet, prev_dir)
        lines.append(f"  {name}: {{ img: '__IMG(armor_glow_{name}.webp)__', cols: {cols}, cw: {cw}, ch: {ch}, n: {n}, fps: {fps}, ox: {ox}, oy: {oy} }},")

    if not args.no_write:
        js = (
            '/* KAGE: armor glow sheets baked in Godot (godot/armor-glow; generated by tools/armor-glow/pack.py; do not edit).\n'
            '   Each: cols, cell cw x ch, n frames (a seamless loop), fps (suggested playback), ox/oy (the origin in a cell, px).\n'
            '   Rendered on black: played additively. */\n'
            'const ARMOR_GLOW_SHEETS = {\n' + '\n'.join(lines) + '\n};\n'
        )
        path = os.path.join(ROOT, 'src', 'js', '34b-armor-glow-sheets.js')
        with open(path, 'w', newline='\n') as f:
            f.write(js)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
